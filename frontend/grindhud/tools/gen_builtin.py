#!/usr/bin/env python3
"""Regenerate builtin_defs.c from defs/<platform>/*.ghud.

Built-in definitions let the core work with no files on the device: a .ghud in
the frontend's system/grindhud/<platform>/ still takes priority (and hot
reloads), but if there is none, the copy compiled into the core is used.

Run after editing any file under defs/:  python3 tools/gen_builtin.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFS = os.path.join(ROOT, "defs")
OUT = os.path.join(ROOT, "builtin_defs.c")


def c_string(text):
    out = []
    for line in text.splitlines(True):
        esc = line.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
        out.append('   "%s"' % esc)
    return "\n".join(out) if out else '   ""'


def main():
    entries = []
    for platform in sorted(os.listdir(DEFS)):
        pdir = os.path.join(DEFS, platform)
        if not os.path.isdir(pdir):
            continue
        for name in sorted(os.listdir(pdir)):
            if not name.endswith(".ghud"):
                continue
            with open(os.path.join(pdir, name), encoding="utf-8") as f:
                text = f.read()
            if not re.search(r"^\s*serial\s", text, re.M):
                raise SystemExit(f"{platform}/{name}: no serial line")
            entries.append((platform, name, text))

    parts = [
        "/* GENERATED by tools/gen_builtin.py from defs/ -- do not edit. */",
        '#include <stddef.h>',
        '#include "builtin_defs.h"',
        "",
    ]
    for i, (platform, name, text) in enumerate(entries):
        parts.append(f"/* {platform}/{name} */")
        parts.append(f"static const char def_{i}[] =\n{c_string(text)};\n")
    parts.append("const ghud_builtin_t ghud_builtins[] = {")
    for i, (platform, name, _) in enumerate(entries):
        parts.append(f'   {{ "{platform}", "{name}", def_{i} }},')
    parts.append("   { NULL, NULL, NULL }")
    parts.append("};")
    parts.append("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print(f"wrote {OUT}: {len(entries)} definition(s)")


if __name__ == "__main__":
    main()
